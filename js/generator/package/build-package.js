// Client-side packaging for the "Custom manual" download: the zip only ever
// contains the one layout/theme/logo/favicon this download actually needs,
// never every brand's/layout's files. `JSZip` is a global provided by
// vendor/jszip.min.js (a plain <script> in generator/index.html).
import { CORE_FILES, LAYOUT_CSS, I18N_FILES, FALLBACK_LOGO, FALLBACK_FAVICON } from './file-manifest.js';

const MIME_EXT = {
  'image/svg+xml': 'svg',
  'image/png': 'png',
  'image/jpeg': 'jpg',
  'image/x-icon': 'ico',
  'image/webp': 'webp',
};

function extFromFile(file) {
  const dot = file.name.lastIndexOf('.');
  if (dot > -1) return file.name.slice(dot + 1).toLowerCase();
  return MIME_EXT[file.type] || 'png';
}

// `path` is project-root-relative, resolved via rootUrl() (js/generator/paths.js).
async function fetchText(path) {
  const res = await fetch(rootUrl(path));
  if (!res.ok) throw new Error(`Could not fetch ${path} (${res.status})`);
  return res.text();
}

async function fetchBuffer(path) {
  const res = await fetch(rootUrl(path));
  if (!res.ok) throw new Error(`Could not fetch ${path} (${res.status})`);
  return res.arrayBuffer();
}

// Fills the base-palette variables into a copy of themes/theme-generic.css.
function buildThemeCustomCss(template, { colors, componentColors = {}, borderRadius, fontHeading, fontBody, logoPath, fontFaces = [] }) {
  const replacements = {
    '--color-primary': colors.primary,
    '--color-secondary': colors.secondary,
    '--color-text': colors.text,
    '--color-bg': colors.bg,
    '--font-heading': fontHeading,
    '--font-body': fontBody,
    '--border-radius': borderRadius,
    '--logo-url': `url('../${logoPath}')`,
  };
  let css = template;
  for (const [variable, value] of Object.entries(replacements)) {
    const re = new RegExp(`(${variable}:)[^;]+;`);
    css = css.replace(re, `$1 ${value};`);
  }
  const facesBlock = fontFaces.length ? fontFaces.join('\n') + '\n\n' : '';
  const colorScheme = isDarkBackground(colors.bg) ? 'dark' : 'light';
  const schemeBlock = `\n\n/* Derived from --color-bg — see themes/theme-schema.md's --color-scheme entry. */\n:root {\n  --color-scheme: ${colorScheme};\n}\n`;
  // Appended as a separate :root rule rather than patched into the
  // template's own component-color block, which lives inside a CSS
  // comment (see themes/theme-generic.css).
  const componentEntries = Object.entries(componentColors);
  const componentBlock = componentEntries.length
    ? `\n\n/* Component colors set in the generator — see themes/theme-schema.md. */\n:root {\n${componentEntries
        .map(([cssVar, value]) => `  ${cssVar}: ${value};`)
        .join('\n')}\n}\n`
    : '';
  return facesBlock + css + schemeBlock + componentBlock;
}

function buildFontFace(family, relativeAssetPath) {
  return `@font-face {\n  font-family: '${family}';\n  src: url('../${relativeAssetPath}');\n}`;
}

